// FUNÇÃO DE DETECÇÃO DE DOMÍNIO
// ═══════════════════════════════════════════════════════════════════════════════

export interface DomainDetection {
  domain: string;
  confidence: number;
  levels: number[];
  keywords: string[];
}

export function detectDomain(prompt: string): DomainDetection[] {
  const promptLower = prompt.toLowerCase();
  const detections: DomainDetection[] = [];

  const domainMap: Record<string, { keywords: string[]; levels: number[] }> = {
    'fintech': {
      keywords: ['banco', 'bank', 'pix', 'pagamento', 'payment', 'transferência', 'carteira', 'wallet', 'fintech'],
      levels: [0, 1, 2, 3, 13, 20]
    },
    'iot': {
      keywords: ['iot', 'sensor', 'arduino', 'esp32', 'raspberry', 'mqtt', 'embarcado', 'embedded'],
      levels: [0, 1, 2, 3, 17, 20]
    },
    'game': {
      keywords: ['jogo', 'game', 'unity', 'unreal', 'godot', 'física', 'shader', '3d', '2d'],
      levels: [0, 1, 2, 16]
    },
    'mobile': {
      keywords: ['mobile', 'app', 'ios', 'android', 'flutter', 'react native', 'swift', 'kotlin'],
      levels: [0, 1, 2, 3, 15]
    },
    'realtime': {
      keywords: ['realtime', 'tempo real', 'websocket', 'chat', 'colaborativo', 'live'],
      levels: [0, 1, 2, 3, 14]
    },
    'security': {
      keywords: ['segurança', 'security', 'auth', 'pentest', 'owasp', 'vault'],
      levels: [0, 1, 2, 3, 13]
    },
    'arvr': {
      keywords: ['ar', 'vr', 'realidade aumentada', 'realidade virtual', 'metaverso', 'webxr'],
      levels: [0, 1, 2, 18]
    },
    'edge': {
      keywords: ['edge', 'cloudflare', 'serverless', 'lambda', 'workers', 'cdn'],
      levels: [0, 1, 2, 19]
    },
    'observability': {
      keywords: ['monitoramento', 'logs', 'métricas', 'grafana', 'prometheus', 'observability'],
      levels: [0, 1, 2, 20]
    },
    'web3': {
      keywords: ['blockchain', 'web3', 'smart contract', 'solidity', 'dao', 'nft', 'ethereum'],
      levels: [0, 1, 2, 3, 13]
    },
    'ml': {
      keywords: ['machine learning', 'ml', 'pytorch', 'tensorflow', 'modelo', 'training', 'neural'],
      levels: [0, 1, 2, 3, 20]
    }
  };

  for (const [domain, config] of Object.entries(domainMap)) {
    const matchedKeywords = config.keywords.filter(kw => promptLower.includes(kw));
    if (matchedKeywords.length > 0) {
      detections.push({
        domain,
        confidence: matchedKeywords.length / config.keywords.length,
        levels: config.levels,
        keywords: matchedKeywords
      });
    }
  }

  return detections.sort((a, b) => b.confidence - a.confidence);
}

