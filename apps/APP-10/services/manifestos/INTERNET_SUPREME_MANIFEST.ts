/**
 * Verifica se um tópico ativa este manifesto
 */
export function shouldActivateInternetManifest(input: string): boolean {
  const lowerInput = input.toLowerCase();
  return INTERNET_SUPREME_MANIFEST.metadata.activationKeywords.some(
    keyword => lowerInput.includes(keyword.toLowerCase())
  );
}

/**
 * Retorna informações sobre um protocolo específico
 */
export function getProtocolInfo(protocolName: string): any {
  const protocols = INTERNET_SUPREME_MANIFEST.protocols;
  const lowerName = protocolName.toLowerCase();
  
  for (const [key, value] of Object.entries(protocols)) {
    if (key.toLowerCase() === lowerName || 
        (value as any).name?.toLowerCase().includes(lowerName)) {
      return { key, ...value };
    }
  }
  return null;
}

